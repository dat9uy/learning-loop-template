// ── 1. Precedence: promoted-rule escalate beats hard-block ──

test("promoted-rule escalate beats a records/** path-write hard-block", () => {
  const root = makeRoot();
  // The promoted rule fires on the same command that hard-blocks on
  // records/**; the evaluate-bash-gate.js early return keeps the escalate.
  writePromotedRule(root, { id: "rule-precedence-path", pattern: "records/meta" });
  const result = evaluateBashGate({ command: "echo x > records/meta/test.json", root });
  assert.strictEqual(result.decision, "escalate");
  assert.strictEqual(result.rule_id, "rule-precedence-path");
  assert.strictEqual(result.hard_block, undefined, "escalate must not be a hard block");
});

test("promoted-rule escalate beats a side-effect-import hard-block", () => {
  const root = makeRoot();
  writePromotedRule(root, { id: "rule-precedence-import", pattern: "vnstock_data" });
  const result = evaluateBashGate({ command: 'python -c "import vnstock_data"', root });
  assert.strictEqual(result.decision, "escalate");
  assert.strictEqual(result.rule_id, "rule-precedence-import");
  assert.notStrictEqual(result.constraint_type, "side-effect-import", "the import hard-block must not win");
});

// ── 2. Precedence: constraint hard-block vs path hard-block ──

test("constraint hard-block beats a path-write hard-block (fold order)", () => {
  const root = makeRoot();
  const result = evaluateBashGate({
    command: 'python -c "import vnstock_data" && echo x > records/meta/test.json',
    root,
  });
  assert.strictEqual(result.decision, "block");
  assert.strictEqual(result.hard_block, true);
  assert.strictEqual(result.constraint_type, "side-effect-import", "constraint hard-block must win the fold");
});

// ── 3. Precedence: first-class constraint + gate-verb double-match ──

test("constraint soft-block + gate-verb soft-block → constraint result survives", () => {
  const root = makeRoot();
  const result = evaluateBashGate({ command: "pip install vnstock && bash -c 'echo hi'", root });
  assert.strictEqual(result.decision, "block");
  assert.strictEqual(result.constraint_type, "package-manager", "the constraint result must survive the replace logic");
});

test("constraint ok + gate-verb soft-block → gate-verb replaces the constraint result", () => {
  const root = makeRoot();
  writeRuntimeState(root, [
    { id: "obs-vnstock", kind: "budget-state", status: "active", affected_system: "vnstock", timestamp: new Date().toISOString() },
  ]);
  const result = evaluateBashGate({ command: "pip install vnstock && bash -c 'echo hi'", root });
  assert.strictEqual(result.decision, "block");
  assert.strictEqual(result.constraint_type, "gate-verb:bash", "the stricter non-ok gate-verb must replace the ok constraint");
});

test("constraint ok + gate-verb ok → ok", () => {
  const root = makeRoot();
  writeRuntimeState(root, [
    { id: "obs-vnstock", kind: "budget-state", status: "active", affected_system: "vnstock", timestamp: new Date().toISOString() },
    { id: "obs-bash", kind: "budget-state", status: "active", affected_system: "gate-verb:bash", timestamp: new Date().toISOString() },
  ]);
  const result = evaluateBashGate({ command: "pip install vnstock && bash -c 'echo hi'", root });
  assert.strictEqual(result.decision, "ok");
});

// ── 4. Promoted-rule verbatim reason + complete metadata ──

test("promoted-rule escalate carries the verbatim reason and complete metadata", () => {
  const root = makeRoot();
  writePromotedRule(root, { id: "rule-metadata", pattern: "\\bdocker\\b" });
  const result = evaluateBashGate({ command: "docker run ubuntu", root });
  assert.strictEqual(result.decision, "escalate");
  assert.strictEqual(result.reason, 'Promoted rule "rule-metadata" matched: \\bdocker\\b');
  assert.strictEqual(result.rule_id, "rule-metadata");
  assert.strictEqual(result.meta_state_id, "rule-metadata");
  assert.strictEqual(result.pattern_type, "regex");
  assert.strictEqual(result.event_source, "bash-gate-evaluator");
  assert.strictEqual(result.match_origin, "executable");
  assert.strictEqual(result.candidate_kind, "ordinary-rule-fire");
});

// ── 5. Staleness escalate: observation_id + reason text ──

test("staleness escalate populates observation_id and the reason text", () => {
  const root = makeRoot();
  const observationUpdatedAt = new Date(Date.now() - 10 * 60 * 1000).toISOString();
  const stateChangeAt = new Date().toISOString();
  writeRuntimeState(root, [
    {
      id: "obs-stale-escalate",
      kind: "budget-state",
      status: "active",
      affected_system: "vnstock",
      timestamp: observationUpdatedAt,
    },
  ]);
  const markerPath = join(root, "marker.json");
  writeFileSync(markerPath, JSON.stringify({ timestamp: stateChangeAt }));
  const previousMarkerPath = process.env.GATE_MARKER_PATH;
  process.env.GATE_MARKER_PATH = markerPath;
  try {
    const result = evaluateBashGate({ command: "pip install vnstock", root });
    assert.strictEqual(result.decision, "escalate");
    assert.strictEqual(result.inbound_gate, true);
    assert.strictEqual(result.observation_id, "obs-stale-escalate");
    assert.strictEqual(
      result.reason,
      `Observation "obs-stale-escalate" updated at ${observationUpdatedAt}, but operator sent state-change at ${stateChangeAt}. Observation may be stale. Update before proceeding.`,
    );
  } finally {
    if (previousMarkerPath === undefined) delete process.env.GATE_MARKER_PATH;
    else process.env.GATE_MARKER_PATH = previousMarkerPath;
  }
});

// ── 6. Root defaulting ──

test("evaluateBashGate without root uses GATE_ROOT's rule registry", () => {
  const tempRoot = makeRoot();
  writePromotedRule(tempRoot, { id: "rule-only-in-temp-root", pattern: "\\bno-such-cmd\\b" });
  withGateRoot(tempRoot, () => {
    const result = evaluateBashGate({ command: "no-such-cmd --flag" });
    assert.strictEqual(result.decision, "escalate");
    assert.strictEqual(result.rule_id, "rule-only-in-temp-root", "root-less evaluation must resolve GATE_ROOT");
  });
});

test("evaluateBashGate without root uses the records-walk fallback", () => {
  withGateRoot(undefined, () => {
    const result = evaluateBashGate({ command: "vitest run | tail" });
    assert.strictEqual(result.decision, "escalate");
    assert.strictEqual(result.rule_id, "rule-no-raw-stdout-vitest");
    assert.strictEqual(
      result.reason,
      'Promoted rule "rule-no-raw-stdout-vitest" matched: (vitest run|pnpm test\\b).*\\| *(tail|head|grep)\\b',
    );
  });
});

