// ── helpers ──

function makeRoot() {
  return mkdtempSync(join(tmpdir(), "preservation-baseline-"));
}

function withGateRoot(root, callback) {
  const previous = process.env.GATE_ROOT;
  if (root === undefined) {
    delete process.env.GATE_ROOT;
  } else {
    process.env.GATE_ROOT = root;
  }
  try {
    return callback();
  } finally {
    if (previous === undefined) {
      delete process.env.GATE_ROOT;
    } else {
      process.env.GATE_ROOT = previous;
    }
  }
}

function writeRuntimeState(root, entries) {
  const lines = entries.map((e) => JSON.stringify(e)).join("\n");
  writeFileSync(join(root, "runtime-state.jsonl"), lines + "\n");
}

// Write a promoted regex rule into the fixture root's meta-state.jsonl.
function writePromotedRule(root, { id, pattern }) {
  const rule = JSON.stringify({
    id,
    entry_kind: "rule",
    origin: "meta-test-origin",
    status: "active",
    internalization_level: "I3", evidence_code_ref: "test-rule-contract.js",
    pattern_type: "regex",
    pattern,
    description: "A sufficiently long test description for schema validation to pass.",
    promoted_at: new Date().toISOString(),
    promoted_by: "test",
  });
  writeFileSync(join(root, "meta-state.jsonl"), rule + "\n");
}

