test("decision-log path-prefix looseness: absolute / .// / .git-style prefixes all block with the dedicated reason", () => {
  const root = makeRoot();
  const spellings = [
    "echo x >> /repo/.claude/coordination/.gate-decision.log",
    "echo x >> .//.claude//coordination//.gate-decision.log",
    "echo x >> .git/.claude/coordination/.gate-decision.log",
  ];
  for (const command of spellings) {
    const result = evaluateBashGate({ command, root });
    assert.strictEqual(result.decision, "block", `expected block for ${command}`);
    assert.strictEqual(result.hard_block, true, `expected hard block for ${command}`);
    assert.strictEqual(result.reason, DECISION_LOG_WRITE_REASON, `dedicated reason for ${command}`);
  }
});

test("decision-log accepted over-match: .gate-decision.log.backup → block with the dedicated reason", () => {
  const root = makeRoot();
  const result = evaluateBashGate({ command: "echo x >> .claude/coordination/.gate-decision.log.backup", root });
  assert.strictEqual(result.decision, "block");
  assert.strictEqual(result.hard_block, true);
  assert.strictEqual(result.reason, DECISION_LOG_WRITE_REASON);
});

// ── 10. Inbound gate: stale_signature, suppression, steering pointer ──

function writeStaleObservation(root, { id = "obs-stale" } = {}) {
  writeRuntimeState(root, [
    {
      id,
      kind: "budget-state",
      status: "active",
      affected_system: "vnstock",
      timestamp: new Date(Date.now() - 31 * 60 * 1000).toISOString(),
    },
  ]);
}

test("inbound-gate warn decision carries stale_signature", () => {
  const root = makeRoot();
  writeStaleObservation(root);
  const result = evaluateInboundGate({ prompt: "I cleared the device", root });
  assert.strictEqual(result.decision, "warn");
  assert.ok(result.stale_signature, "stale_signature must be populated on a warn");
  assert.strictEqual(result.stale_signature, "obs-stale");
});

test("same stale signature within the suppress window → 'already surfaced' pointer", () => {
  const root = makeRoot();
  writeStaleObservation(root);
  const now = Date.now();
  const first = evaluateInboundGate({ prompt: "I cleared the device", root, now });
  const second = evaluateInboundGate({
    prompt: "I cleared the device",
    root,
    priorSignature: first.stale_signature,
    priorTs: now - 1000,
    now,
  });
  assert.strictEqual(second.decision, "warn");
  assert.ok(second.context_message.includes("already surfaced this session"), "repeat within window must collapse to the one-line pointer");
  assert.ok(!second.context_message.includes("Operator message contains a state-change signal"), "the full pointer must not re-emit");
});

test("expired suppress window re-emits the full pointer", () => {
  const root = makeRoot();
  writeStaleObservation(root);
  const now = Date.now();
  const first = evaluateInboundGate({ prompt: "I cleared the device", root, now });
  const expired = evaluateInboundGate({
    prompt: "I cleared the device",
    root,
    priorSignature: first.stale_signature,
    priorTs: now - SUPPRESS_WINDOW_MS - 1000,
    now,
  });
  assert.strictEqual(expired.decision, "warn");
  assert.ok(!expired.context_message.includes("already surfaced this session"), "an expired window must re-emit the full pointer");
  assert.ok(expired.context_message.includes("state-change signal"), "the full pointer must re-emit");
});

test("changed stale signature re-emits the full pointer", () => {
  const root = makeRoot();
  writeStaleObservation(root, { id: "obs-a" });
  const now = Date.now();
  evaluateInboundGate({ prompt: "I cleared the device", root, now });
  // Surface a second stale observation alongside the first → the signature changes.
  writeRuntimeState(root, [
    {
      id: "obs-a",
      kind: "budget-state",
      status: "active",
      affected_system: "vnstock",
      timestamp: new Date(Date.now() - 31 * 60 * 1000).toISOString(),
    },
    {
      id: "obs-b",
      kind: "budget-state",
      status: "active",
      affected_system: "vnstock",
      timestamp: new Date(Date.now() - 31 * 60 * 1000).toISOString(),
    },
  ]);
  const changed = evaluateInboundGate({
    prompt: "I cleared the device",
    root,
    priorSignature: "obs-a",
    priorTs: now - 1000,
    now,
  });
  assert.strictEqual(changed.decision, "warn");
  assert.strictEqual(changed.stale_signature, "obs-a,obs-b");
  assert.ok(!changed.context_message.includes("already surfaced this session"), "a changed stale set must re-emit");
});

test("buildSteeringPointer returns the canonical pull pointer", () => {
  assert.strictEqual(
    buildSteeringPointer(),
    "Loop steering (pull): loop_describe({tier:'warm'}) | hints: .claude/session-context.json | one: loop_get_instruction({key})",
  );
});
